""" ports

Protocols (ports) for dataset application layer.
Application code depends on these protocols, not infra implementations.
"""

from __future__ import annotations

from typing import Protocol, Any, Optional, Sequence

class DatasetRepositoryPort(Protocol):
    def get_by_id(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_by_name(self, *args: Any, **kwargs: Any) -> Any: ...
    def list(self, *args: Any, **kwargs: Any) -> Any: ...
    def create(self, *args: Any, **kwargs: Any) -> Any: ...
    def update_stats(self, *args: Any, **kwargs: Any) -> Any: ...

class DocumentRepositoryPort(Protocol):
    def get_by_id(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_by_key(self, *args: Any, **kwargs: Any) -> Any: ...
    def list_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_next_version(self, *args: Any, **kwargs: Any) -> Any: ...
    def count_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...

class ChunkRepositoryPort(Protocol):
    def list_by_document(self, *args: Any, **kwargs: Any) -> Any: ...
    def list_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...
    def count_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...

class IndexRepositoryPort(Protocol):
    def get_by_id(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_by_name(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_primary(self, *args: Any, **kwargs: Any) -> Any: ...
    def list_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...


class IngestTaskRepositoryPort(Protocol):
    def create(self, *args: Any, **kwargs: Any) -> Any: ...
    def get_by_id(self, *args: Any, **kwargs: Any) -> Any: ...
    def list_pending(self, *args: Any, **kwargs: Any) -> Any: ...
    def list_by_dataset(self, *args: Any, **kwargs: Any) -> Any: ...
    def claim_next(self, *args: Any, **kwargs: Any) -> Any: ...
    def update_status(self, *args: Any, **kwargs: Any) -> Any: ...
